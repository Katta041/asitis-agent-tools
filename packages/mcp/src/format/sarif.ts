// asitis lint --format sarif (SARIF 2.1.0). Owner: WP1.
// Field mapping is in docs/cli-contract.md. Spec: OASIS SARIF 2.1.0 errata 01,
// https://docs.oasis-open.org/sarif/sarif/v2.1.0/errata01/os/sarif-v2.1.0-errata01-os-complete.html
// (read 14 October 2026): artifactLocation.uri is a URI reference, so path segments are
// percent-encoded (3.4.3); columnKind utf16CodeUnits matches how findings count columns (3.14.22);
// suppressed results stay in the log with suppressions[] (3.27.23). GitHub code scanning uses
// partialFingerprints and properties["security-severity"]:
// https://docs.github.com/en/code-security/code-scanning/integrating-with-code-scanning/sarif-support-for-code-scanning
// (read 14 October 2026).

import type { Category, Finding, FindingSeverity, LintReport } from "../findings.js";
import { activeRules, type RuleMeta } from "../rules/registry.js";

export const SARIF_SCHEMA = "https://json.schemastore.org/sarif-2.1.0.json";
/** Rule pages, generated by WP8 into docs/rules/. */
export const RULE_DOCS = "https://github.com/Katta041/asitis-agent-tools/blob/main/docs/rules/";

const TAGS: Record<Category, string[]> = {
  security: ["security"],
  format: ["steering"],
  budget: ["budget"],
  drift: ["drift"],
  config: ["steering"],
};

const SECURITY_SEVERITY: Record<FindingSeverity, string> = { error: "8.0", warning: "5.0", note: "2.0" };

/** A root-relative POSIX path as a relative URI reference: every segment percent-encoded. */
export function toUri(p: string): string {
  return p.split("/").map((s) => encodeURIComponent(s)).join("/");
}

function ruleDescriptor(r: RuleMeta): Record<string, unknown> {
  const properties: Record<string, unknown> = { tags: TAGS[r.category] };
  if (r.category === "security") properties["security-severity"] = SECURITY_SEVERITY[r.defaultSeverity];
  return {
    id: r.id,
    shortDescription: { text: r.summary },
    fullDescription: { text: r.why },
    helpUri: `${RULE_DOCS}${encodeURIComponent(r.id)}.md`,
    defaultConfiguration: { level: r.defaultSeverity },
    properties,
  };
}

function result(f: Finding, index: ReadonlyMap<string, number>): Record<string, unknown> {
  const artifactLocation = { uri: toUri(f.path), uriBaseId: "%SRCROOT%" };
  const out: Record<string, unknown> = { ruleId: f.ruleId };
  const i = index.get(f.ruleId);
  if (i !== undefined) out["ruleIndex"] = i;
  out["level"] = f.severity;
  out["message"] = { text: f.message };
  out["locations"] = [
    {
      physicalLocation: {
        artifactLocation,
        region: { startLine: f.line, startColumn: f.column, endLine: f.endLine, endColumn: f.endColumn },
      },
    },
  ];
  if (f.fingerprint) out["partialFingerprints"] = { "asitis/v1": f.fingerprint };
  if (f.suppressed) {
    out["suppressions"] = [{ kind: f.suppressed.kind, ...(f.suppressed.justification ? { justification: f.suppressed.justification } : {}) }];
  }
  if (f.fix) {
    out["fixes"] = [
      {
        description: { text: `${f.fix.safety} fix for ${f.ruleId}` },
        artifactChanges: [
          {
            artifactLocation,
            replacements: f.fix.edits.map((e) => ({
              deletedRegion: { byteOffset: e.startByte, byteLength: e.endByte - e.startByte },
              insertedContent: { text: e.replacement },
            })),
          },
        ],
      },
    ];
  }
  return out;
}

export function formatSarif(report: LintReport): string {
  const rules = activeRules();
  const index = new Map(rules.map((r, i) => [r.id, i]));
  const log = {
    $schema: SARIF_SCHEMA,
    version: "2.1.0",
    runs: [
      {
        tool: {
          driver: {
            name: "AsItIs",
            version: report.tool.version,
            informationUri: "https://asitis.app",
            rules: rules.map(ruleDescriptor),
          },
        },
        columnKind: "utf16CodeUnits",
        invocations: [{ executionSuccessful: true }],
        results: report.findings.map((f) => result(f, index)),
      },
    ],
  };
  return `${JSON.stringify(log, null, 2)}\n`;
}
